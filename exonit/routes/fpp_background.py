"""``GET /api/fpp_background/{tic_id}``: cached Galaxia field-star population for FPP.

FPP fix plan step 5 (section 4.5, design A).  Read-only: the population is
generated by the server-side batch (``exonit.fpp_background.prefetch_backgrounds``,
CLI ``scripts/fpp_background_prefetch.py``) BEFORE the FPP phase; a miss is a
404, never an on-demand Galaxia run (a worker request must not wait ~12 s on a
subprocess, and workers have no external connectivity to fall back on).

The response body is the stored canonical JSON document byte for byte, so
``sha256(body) == X-Blob-Sha256`` and what the worker parses is what was hashed.
Query ``population_version`` pins a version; without it the version of the
pinned local install is used; a host without the install and without the query
parameter answers 503 (a version is never chosen implicitly).
"""

from typing import Optional

from fastapi import Query, Request
from fastapi.responses import JSONResponse, Response

from exonit import fpp_background as _fb
from exonit.fpp_background import FppBackgroundStore, population_family, serve_population
from exonit import fpp_galaxia_store
from exonit.routes.deps import ServerDeps


def register(app, deps: ServerDeps) -> None:
    db = deps.db
    _check_auth = deps.check_auth

    @app.get("/api/health/fpp_population")
    def health_fpp_population():
        """Live health of the FPP population source (monitoring; no auth, no paths).  200 when the source
        is usable (store switch off, or store on and a live probe TIC verified end to end); 503 when the
        store is on and unusable (mount gone, files changed, family mismatch): FPP is then refused."""
        rep = fpp_galaxia_store.health()
        return JSONResponse(rep, status_code=200 if rep["ok"] else 503)

    @app.get("/api/fpp_background/{tic_id}")
    def get_fpp_background(tic_id: str, request: Request,
                           population_version: Optional[str] = Query(None)):
        if not _check_auth(request):
            return JSONResponse({"error": "unauthorized"}, status_code=401)
        try:
            tic_id = str(int(tic_id))               # "/007" == 7
        except ValueError:
            return JSONResponse({"error": "Invalid tic_id"}, status_code=400)
        store_on = fpp_galaxia_store.store_index_path() is not None
        # store on: the family is required and checked by the store itself (below)
        family = None if (population_version or store_on) else population_family()
        version = population_version or (None if (family or store_on) else _fb.current_population_version())
        if version is None and family is None and not store_on:
            # No pinned install on this host, no configured family and the caller did not say which
            # version it expects: never pick one implicitly (determinism first).
            return JSONResponse(
                {"error": "no pinned Galaxia install on this host; pass ?population_version=<version>"},
                status_code=503)
        try:
            galaxia = fpp_galaxia_store.active_store()
        except fpp_galaxia_store.GalaxiaStoreError as exc:
            fpp_galaxia_store.log_store_error(exc)
            return JSONResponse({"error": f"fpp_background unavailable: {exc}",
                                 "error_type": type(exc).__name__,
                                 "population_store": fpp_galaxia_store.STORE_NAME}, status_code=503)
        if galaxia is not None:
            # The materialized store is the only source: exact pin or the TIC's single family row;
            # a miss is a 404, never answered from the fpp_background table.
            try:
                hit = (galaxia.get(tic_id, population_version) if population_version
                       else galaxia.get_by_family(tic_id, galaxia.family))
            except Exception as exc:  # noqa: BLE001 - failed verification: refuse
                return JSONResponse({"error": f"fpp_background unavailable: {exc}",
                                     "error_type": type(exc).__name__,
                                     "population_store": fpp_galaxia_store.STORE_NAME}, status_code=503)
            if hit is None:
                return JSONResponse(
                    {"error": f"no fpp_background for TIC {tic_id} in the galaxia store",
                     "population_version": population_version, "population_family": galaxia.family,
                     "population_store": fpp_galaxia_store.STORE_NAME,
                     "run_id": galaxia.meta["run_id"]}, status_code=404)
            return Response(
                content=hit["payload"], media_type="application/json",
                headers={"X-Blob-Sha256": hit["sha256"],
                         "X-Population-Version": hit["population_version"],
                         "X-Population-Family": galaxia.family,
                         "X-N-Comp": str(hit["n_comp"]),
                         "X-Population-Store": fpp_galaxia_store.STORE_NAME})
        try:
            store = FppBackgroundStore(db.backend)
            # ?population_version= pins one exact row; else the configured FAMILY (by TIC), else the
            # legacy exact version of the local install.
            hit = store.get(tic_id, version) if version else store.get_by_family(tic_id, family)
        except Exception as exc:  # noqa: BLE001 - e.g. table not yet created (step 6), hash mismatch
            return JSONResponse({"error": f"fpp_background unavailable: {exc}"}, status_code=503)
        if hit is None:
            return JSONResponse(
                {"error": f"no fpp_background for TIC {tic_id}", "population_version": version,
                 "population_family": family,
                 "hint": "populations are prefetched in batch before the FPP phase"},
                status_code=404)
        return Response(
            content=hit["payload"], media_type="application/json",
            headers={"X-Blob-Sha256": hit["sha256"],
                     "X-Population-Version": hit["population_version"],
                     "X-N-Comp": str(hit["n_comp"])})
